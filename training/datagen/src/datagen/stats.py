"""Write stats.md for a generated dataset and copy it to the research notes.

    uv run python -m datagen.stats --out ../../data/synthetic
"""
from __future__ import annotations

import argparse
import json
import shutil
from collections import Counter, defaultdict
from pathlib import Path

RESEARCH_COPY = Path(__file__).resolve().parents[4] / "docs/research/2026-10-24-pii-dataset/work/synthetic-stats.md"
DOC_BUCKETS = [(0, 200), (200, 600), (600, 1500), (1500, 3000), (3000, 6000), (6000, 12000), (12000, 10**9)]


def _pct(xs: list[int], q: float) -> int:
    if not xs:
        return 0
    return xs[min(len(xs) - 1, int(q * len(xs)))]


def _bucket_label(a: int, b: int) -> str:
    return f">= {a:,}" if b >= 10**9 else f"{a:,} to {b - 1:,}"


def _table(head: list[str], rows: list[list]) -> list[str]:
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for r in rows:
        out.append("| " + " | ".join(str(x) for x in r) + " |")
    return out


def _share(a: int, b: int) -> str:
    return f"{100.0 * a / b:.1f}%" if b else "0%"


def collect(out: Path) -> dict:
    docs = Counter()
    neg = Counter()
    chars = defaultdict(list)
    ents_per_type = Counter()
    docs_with_type = Counter()
    hard = Counter()
    docs_with_hard = 0
    keep = Counter()
    lengths = []
    n_chunks_doc = Counter()
    near = Counter()
    variants = set()
    split_docs = Counter()
    ents_by_dt = Counter()
    n = 0
    for line in open(out / "docs.jsonl", encoding="utf-8"):
        r = json.loads(line)
        n += 1
        dt = r["doc_type"]
        docs[dt] += 1
        m = r["meta"]
        neg[dt] += m["negative"]
        L = len(r["text"])
        chars[dt].append(L)
        lengths.append(L)
        ents_by_dt[dt] += len(r["entities"])
        seen = set()
        for e in r["entities"]:
            ents_per_type[e["type"]] += 1
            seen.add(e["type"])
        for t in seen:
            docs_with_type[t] += 1
        for h in m["hard_cases"]:
            hard[h["kind"]] += 1
        docs_with_hard += bool(m["hard_cases"])
        for k in m["keep_traps"]:
            keep[k["kind"]] += 1
        n_chunks_doc[m.get("n_chunks", 1)] += 1
        near[dt] += m.get("near_dup", False)
        variants.add(m["variant_id"])
        split_docs[r["split"]] += 1
    chunk_lens = []
    split_chunks = Counter()
    chunk_neg = 0
    chunk_skel = Counter()
    for line in open(out / "chunks.jsonl", encoding="utf-8"):
        c = json.loads(line)
        chunk_lens.append(len(c["text"]))
        split_chunks[c["split"]] += 1
        chunk_neg += not c["entities"]
        chunk_skel[c["meta"]["skeleton_hash"]] += 1
    mubit = {}
    for name in ("mubit_round1", "mubit_round2", "mubit_corrections", "mubit_eval"):
        p = out / f"{name}.jsonl"
        if not p.exists():
            continue
        dts, types, hk = Counter(), Counter(), Counter()
        cnt = negs = with_hard = with_custom = 0
        docs_m = set()
        lens = []
        for line in open(p, encoding="utf-8"):
            c = json.loads(line)
            cnt += 1
            docs_m.add(c["doc_id"])
            dts[c["doc_type"]] += 1
            ts = {e["type"] for e in c["entities"]}
            for t in ts:
                types[t] += 1
            negs += not c["entities"]
            kinds = {h["kind"] for h in c["meta"]["hard_cases"]}
            with_hard += bool(kinds)
            for k in kinds:
                hk[k] += 1
            with_custom += "CUSTOM" in ts
            lens.append(len(c["text"]))
        lens.sort()
        mubit[name] = dict(chunks=cnt, docs=len(docs_m), doc_types=dts, types=types, neg=negs, with_hard=with_hard,
                           with_custom=with_custom, hard_kinds=len(hk), p50=_pct(lens, 0.5), max=lens[-1] if lens else 0)
    manifest = json.loads((out / "manifest.json").read_text()) if (out / "manifest.json").exists() else {}
    pdf = json.loads((out / "pdfs" / "pdf_report.json").read_text()) if (out / "pdfs" / "pdf_report.json").exists() else None
    lengths.sort()
    chunk_lens.sort()
    return dict(n=n, docs=docs, neg=neg, chars=chars, ents_per_type=ents_per_type, docs_with_type=docs_with_type,
                hard=hard, docs_with_hard=docs_with_hard, keep=keep, lengths=lengths, n_chunks_doc=n_chunks_doc,
                near=near, variants=variants, split_docs=split_docs, split_chunks=split_chunks, chunk_lens=chunk_lens,
                chunk_neg=chunk_neg, chunk_skel=chunk_skel, mubit=mubit, manifest=manifest, pdf=pdf, ents_by_dt=ents_by_dt)


def render(s: dict) -> str:
    n = s["n"]
    nchunks = len(s["chunk_lens"])
    m = s["manifest"]
    L = []
    L.append("# Synthetic PII dataset: stats")
    L.append("")
    L.append(f"Generated by `datagen` (seed {m.get('seed', '?')}). All personal data is fake. "
             "Regenerate with `uv run python -m datagen.stats --out ../../data/synthetic`.")
    L.append("")
    L.append("## Totals")
    total_neg = sum(s["neg"].values())
    short = s["docs"].get("ai_prompt", 0) + s["docs"].get("chat_messages", 0)
    under600 = sum(1 for x in s["lengths"] if x < 600)
    near_total = sum(s["near"].values())
    dup_chunks = sum(c - 1 for c in s["chunk_skel"].values() if c > 1)
    L += _table(["Metric", "Value"], [
        ["Documents", f"{n:,}"],
        ["Chunks (max 6,000 chars)", f"{nchunks:,}"],
        ["Entity spans", f"{sum(s['ents_per_type'].values()):,}"],
        ["Negative documents (no personal data)", f"{total_neg:,} ({_share(total_neg, n)})"],
        ["Negative chunks", f"{s['chunk_neg']:,} ({_share(s['chunk_neg'], nchunks)})"],
        ["Short messages (ai_prompt + chat_messages)", f"{short:,} ({_share(short, n)})"],
        ["Documents under 600 chars", f"{under600:,} ({_share(under600, n)})"],
        ["Documents with at least one hard case", f"{s['docs_with_hard']:,} ({_share(s['docs_with_hard'], n)})"],
        ["Distinct template/variant ids", f"{len(s['variants']):,}"],
        ["Exact duplicates regenerated during generation", f"{m.get('exact_dup_regenerated', '?')}"],
        ["Exact duplicate rate in output", "0% (exact duplicates are regenerated)"],
        ["Skeleton duplicates (identical after masking PII, zeroing digits, folding case/space)",
         f"{m.get('skeleton_dup_docs', '?')} docs; {dup_chunks:,} chunks ({_share(dup_chunks, nchunks)})"],
        ["Fuzzy near-duplicate documents (MinHash Jaccard >= 0.8 on skeleton word 3-grams vs any earlier doc)",
         f"{near_total:,} ({_share(near_total, n)})"],
        ["Fuzzy near-duplicate chunks (same test, chunk level)",
         f"{m.get('near_dup_chunks', 0):,} ({_share(m.get('near_dup_chunks', 0), nchunks)})"],
        ["Generation time", f"{m.get('seconds', '?')} s ({m.get('docs_per_sec', '?')} docs/s, {m.get('workers', '?')} workers)"],
    ])
    L.append("")
    L.append("## Splits (by document)")
    rows = []
    for sp in ("train", "fresh", "corrections", "eval"):
        rows.append([sp, f"{s['split_docs'][sp]:,}", _share(s["split_docs"][sp], n), f"{s['split_chunks'][sp]:,}"])
    L += _table(["Split", "Docs", "Share", "Chunks"], rows)
    L.append("")
    L.append("## Documents per type")
    rows = []
    for dt, c in sorted(s["docs"].items(), key=lambda x: -x[1]):
        xs = sorted(s["chars"][dt])
        rows.append([dt, f"{c:,}", _share(c, n), f"{s['neg'][dt]:,}", f"{_pct(xs, 0.5):,}", f"{xs[-1]:,}",
                     f"{s['ents_by_dt'][dt] / c:.1f}", f"{s['near'][dt]:,} ({_share(s['near'][dt], c)})"])
    L += _table(["Doc type", "Docs", "Share", "Negatives", "Median chars", "Max chars", "Spans/doc",
                 "Fuzzy near-dup docs"], rows)
    L.append("")
    L.append("## Entity types")
    rows = [[t, f"{c:,}", f"{s['docs_with_type'][t]:,}", _share(s["docs_with_type"][t], n)]
            for t, c in sorted(s["ents_per_type"].items(), key=lambda x: -x[1])]
    L += _table(["Type", "Spans", "Docs containing", "Share of docs"], rows)
    L.append("")
    L.append("## Hard cases (span or region level)")
    L += _table(["Kind", "Count"], [[k, f"{c:,}"] for k, c in s["hard"].most_common()])
    L.append("")
    L.append("## Keep traps (must not be labelled)")
    L += _table(["Kind", "Count"], [[k, f"{c:,}"] for k, c in s["keep"].most_common()])
    L.append("")
    L.append("## Length distribution")
    rows = []
    for a, b in DOC_BUCKETS:
        c = sum(1 for x in s["lengths"] if a <= x < b)
        rows.append([_bucket_label(a, b), f"{c:,}", _share(c, n)])
    L += _table(["Document chars", "Docs", "Share"], rows)
    L.append("")
    xs = s["lengths"]
    cl = s["chunk_lens"]
    L.append(f"Document chars: p10 {_pct(xs, .1):,}, p50 {_pct(xs, .5):,}, p90 {_pct(xs, .9):,}, "
             f"p99 {_pct(xs, .99):,}, max {xs[-1]:,}.  ")
    L.append(f"Chunk chars: p50 {_pct(cl, .5):,}, p90 {_pct(cl, .9):,}, max {cl[-1]:,}.  ")
    L.append("Chunks per document: " + ", ".join(f"{k}: {v:,}" for k, v in sorted(s["n_chunks_doc"].items())) + ".")
    L.append("")
    if s["mubit"]:
        L.append("## Mubit round files")
        rows = []
        for name, d in s["mubit"].items():
            rows.append([f"`{name}.jsonl`", f"{d['chunks']:,}", f"{d['docs']:,}", len(d["doc_types"]),
                         _share(d["neg"], d["chunks"]), _share(d["with_hard"], d["chunks"]),
                         _share(d["with_custom"], d["chunks"]), d["hard_kinds"], f"{d['p50']:,}", f"{d['max']:,}"])
        L += _table(["File", "Chunks", "Docs", "Doc types", "Negative", "With hard case", "With CUSTOM",
                     "Hard-case kinds", "Median chars", "Max chars"], rows)
        L.append("")
        types = sorted({t for d in s["mubit"].values() for t in d["types"]})
        rows = [[t] + [f"{d['types'][t]:,}" for d in s["mubit"].values()] for t in types]
        L.append("Chunks containing each entity type:")
        L.append("")
        L += _table(["Type"] + list(s["mubit"]), rows)
        L.append("")
        dts = sorted({t for d in s["mubit"].values() for t in d["doc_types"]})
        rows = [[t] + [f"{d['doc_types'][t]:,}" for d in s["mubit"].values()] for t in dts]
        L.append("Chunks per doc type:")
        L.append("")
        L += _table(["Doc type"] + list(s["mubit"]), rows)
        L.append("")
    if s["pdf"]:
        p = s["pdf"]
        L.append("## Demo PDFs (render, extract with pdfplumber, re-align gold spans)")
        L += _table(["Metric", "Value"], [
            ["PDFs", p["n_pdfs"]], ["Gold spans", p["spans"]],
            ["Spans not found in extracted text (mismatch rate)", f"{p['missing']} ({p['mismatch_rate']:.2%})"],
            ["Spans found but whitespace changed (line wrap)", f"{p.get('whitespace_changed_rate', 0):.2%}"],
            ["Mean text similarity (source vs extracted, whitespace folded)", p["mean_text_similarity"]],
        ])
        L.append("")
    return "\n".join(L) + "\n"


def write_stats(out: Path, copy_to: Path | None = RESEARCH_COPY) -> Path:
    s = collect(out)
    text = render(s)
    p = out / "stats.md"
    p.write_text(text, encoding="utf-8")
    if copy_to is not None and copy_to.parent.exists():
        shutil.copyfile(p, copy_to)
    return p


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, default=Path("../../data/synthetic"))
    ap.add_argument("--no-copy", action="store_true", help="do not copy stats.md to the research notes")
    a = ap.parse_args(argv)
    p = write_stats(a.out.resolve(), None if a.no_copy else RESEARCH_COPY)
    print(p)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
