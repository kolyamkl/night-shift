"""Turn a Doc builder into a canonical record (text + spans + meta)."""
from __future__ import annotations

import hashlib
import re
from collections import defaultdict

from .core import Doc, render

LICENSE = "synthetic: generated by Veil datagen, contains no real personal data"
_WS = re.compile(r"\s+")
_DIG = re.compile(r"\d")


def norm_hash(text: str) -> str:
    """Exact-duplicate key: case and whitespace insensitive."""
    return hashlib.sha1(_WS.sub(" ", text.lower()).strip().encode()).hexdigest()[:16]


def skeleton(text: str, entities: list[dict]) -> str:
    """Text with every entity replaced by its type, digits zeroed, lower case, whitespace collapsed.
    Two documents with the same skeleton differ only in personal values / numbers (near-duplicates)."""
    parts = []
    last = 0
    for e in entities:
        parts.append(text[last:e["start"]])
        parts.append(f"<{e['type']}>")
        last = e["end"]
    parts.append(text[last:])
    s = "".join(parts).lower()
    s = _DIG.sub("0", s)
    return _WS.sub(" ", s).strip()


def skeleton_hash(text: str, entities: list[dict]) -> str:
    return hashlib.sha1(skeleton(text, entities).encode()).hexdigest()[:16]


def finish(doc: Doc, negative: bool) -> dict:
    text, ents, hard, keep, refs = render(doc.atoms)
    # same person written 3+ different ways in one document
    forms: dict[str, set] = defaultdict(set)
    for e, r in zip(ents, refs):
        if r and e["type"] == "PERSON":
            forms[r].add(e["text"].lower())
    multi = {r for r, f in forms.items() if len(f) >= 3}
    if multi:
        for e, r in zip(ents, refs):
            if r in multi and e["type"] == "PERSON":
                hard.append({"kind": "same_person_3_ways", "start": e["start"], "end": e["end"]})
    # account numbers right next to amounts
    for e in ents:
        if e["type"] in ("BANK_ACCOUNT", "CARD", "SORT_CODE"):
            window = text[max(0, e["start"] - 25): e["end"] + 25]
            if "£" in window or "GBP" in window:
                hard.append({"kind": "account_next_to_amount", "start": e["start"], "end": e["end"]})
    if negative and ents:
        raise ValueError(f"negative {doc.doc_type} doc contains entities: {ents[:3]}")
    hard.sort(key=lambda h: (h["start"], h["end"], h["kind"]))
    # dedupe identical hard-case records
    seen = set()
    hard_u = []
    for h in hard:
        k = (h["kind"], h["start"], h["end"])
        if k not in seen:
            seen.add(k)
            hard_u.append(h)
    return {
        "doc_type": doc.doc_type,
        "text": text,
        "entities": ents,
        "meta": {
            "template_id": doc.template_id,
            "variant_id": doc.variant_id,
            "negative": negative,
            "hard_cases": hard_u,
            "keep_traps": keep,
            "entity_refs": refs,
            "norm_hash": norm_hash(text),
            "skeleton_hash": skeleton_hash(text, ents),
            **doc.meta,
        },
    }
